#!/usr/bin/env python3
"""tests/ga_tests/versions_running/expected.<board>.env from the pins of the tree.

The device suite compares what RUNS with these constants, never with the device
itself. One file per board (its pin file, its CPU arch).
  gen-running-versions.py            write     gen-running-versions.py --check   fail when a file is stale
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
BOARDS = {"ihost": ("buildroot-external/package/hassio/addon-images.json", "armv7"), "dsgw210": ("buildroot-dsgw210/addon-images.json", "aarch64")}

# The DSGW-210 image no longer bakes the Sonoff dongle flasher (Thomas 2026-11-26, d2); there is no
# pinned-but-excluded add-on left, so the expectations list only what runs.


def version(key):
    m = re.search(rf'^\s+{key}:\s*"([0-9.]+)"', (ROOT / "version.yaml").read_text(), re.M)
    if not m:
        sys.exit(f"version.yaml: no {key}")
    return m[1]


def core():
    t = (ROOT / "tests/ga_tests/os_integrity/expected.env").read_text()
    m = re.search(r'^EXPECTED_CORE="([0-9.]+)"', t, re.M)
    if not m:
        sys.exit("os_integrity/expected.env: no EXPECTED_CORE")
    return m[1]


def render(board):
    rel, arch = BOARDS[board]
    pins = json.loads((ROOT / rel).read_text())["addons"]
    if len(pins) < 5:
        sys.exit(f"{rel}: only {len(pins)} pins")
    refs, ahead = [], []
    for k in sorted(pins):
        img = pins[k]["image"].replace("{arch}", arch)
        refs.append(f"{k}={img}:{pins[k]['version']}")
        if pins[k].get("store_ahead"):
            ahead.append(k)
    c, s = core(), version("homeassistant_supervisor")
    return (f"# generated by scripts/gen-running-versions.py from {rel} and version.yaml - do not edit\n"
            f'VR_BOARD="{board}"\nVR_CORE="{c}"\nVR_SUPERVISOR="{s}"\nVR_ADDONS="{" ".join(refs)}"\n'
            f'VR_STORE_AHEAD="{" ".join(ahead)}"\n')


bad = 0
for b in BOARDS:
    p = ROOT / f"tests/ga_tests/versions_running/expected.{b}.env"
    t = render(b)
    if "--check" in sys.argv[1:]:
        if not p.is_file() or p.read_text() != t:
            print(f"STALE {p.relative_to(ROOT)}: run scripts/gen-running-versions.py")
            bad = 1
    else:
        p.write_text(t)
print(f"gen-running-versions: {len(BOARDS)} boards, {'stale' if bad else 'ok'}")
sys.exit(bad)
